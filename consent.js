/*
  Pixel North cookie control (standard kit), engine version 3.
  DO NOT EDIT THIS FILE PER SITE. Every site's settings live in consent-config.js.
  Google Analytics is loaded only after the visitor chooses "Accept analytics".
  Reject is as easy as Accept, and the choice can be changed at any time from
  any element marked data-cookie-settings (for example a footer link).
*/
(function () {
  "use strict";

  var DEFAULTS = {
    gaId: "",                 // GA4 measurement ID, e.g. "G-ABC123XYZ". Empty = no analytics, no banner.
    cookieName: "site_consent",
    version: "v1",            // change to ask everyone again after a policy change
    acceptDays: 365,          // how long an "accept" is remembered
    declineDays: 365,         // how long a "reject" is remembered (agree a figure per client)
    policyUrl: "cookies.html",
    logUrl: null,             // e.g. "/api/consent" to use the audit log (Cloudflare Worker sites only)
    colors: { brand: "#1d4ed8", text: "#1a1a1a", background: "#ffffff", focus: "#d97706" },
    fonts: { body: "system-ui, sans-serif", heading: "system-ui, sans-serif" },
    text: {
      title: "Cookies on this site",
      intro: "We’d like to use Analytics cookies to see how you use this site. They stay off unless you say yes. A cookie that remembers your choice is always on.",
      policyLink: "Cookie policy",
      accept: "Accept analytics",
      reject: "Reject analytics",
      manage: "Choose settings",
      settingsTitle: "Cookie settings",
      essentialName: "Essential",
      essentialDesc: "Remembers your cookie choice. Always on.",
      analyticsName: "Analytics",
      analyticsDesc: "Google Analytics cookies that count visits and show which pages are used. Off unless you turn them on.",
      save: "Save choices",
      cancel: "Cancel"
    }
  };

  function merge(base, extra) {
    var out = {}, k;
    for (k in base) out[k] = base[k];
    if (extra) for (k in extra) {
      out[k] = (base[k] && typeof base[k] === "object" && extra[k] && typeof extra[k] === "object")
        ? merge(base[k], extra[k]) : extra[k];
    }
    return out;
  }

  var C = merge(DEFAULTS, window.COOKIE_CONTROL);
  var GA_ID = String(C.gaId || "");
  var COOKIE = /^[A-Za-z0-9_]{1,40}$/.test(C.cookieName) ? C.cookieName : DEFAULTS.cookieName;
  var VERSION = /^v[0-9]{1,3}$/.test(C.version) ? C.version : DEFAULTS.version;
  var LOG_URL = C.logUrl || null;
  var T = C.text;
  var root, lastFocus;

  function days(n, fallback) {
    n = Number(n);
    return (isFinite(n) && n >= 1 && n <= 730) ? Math.floor(n) : fallback;
  }
  var ACCEPT_AGE = days(C.acceptDays, 365) * 86400;
  var DECLINE_AGE = days(C.declineDays, 365) * 86400;

  function colour(v, fallback) { return /^#[0-9a-fA-F]{3,8}$/.test(v) ? v : fallback; }
  function font(v, fallback) { return typeof v === "string" && v && !/[;{}<>]/.test(v) ? v : fallback; }
  function esc(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }

  // The cookie holds "<version>-<yes|no>.<consent id>", e.g. v2-yes.3f2b...
  // The consent id is a random UUID. It links one visitor's choices together
  // in the audit trail without identifying them.
  function readState() {
    var m = document.cookie.match(new RegExp("(?:^|; )" + COOKIE + "=([^;]*)"));
    var p = m && m[1].match(/^(v[0-9]+)-(yes|no)(?:\.([0-9a-f-]{36}))?$/);
    return p ? { version: p[1], yes: p[2] === "yes", id: p[3] || null } : null;
  }

  function readChoice() {
    var s = readState();
    if (!s || s.version !== VERSION) return null;
    return s.yes;
  }

  function newId() {
    var c = window.crypto;
    if (c && c.randomUUID) return c.randomUUID();
    var b = new Uint8Array(16);
    if (c && c.getRandomValues) c.getRandomValues(b);
    else for (var i = 0; i < 16; i++) b[i] = Math.floor(Math.random() * 256);
    b[6] = (b[6] & 0x0f) | 0x40;
    b[8] = (b[8] & 0x3f) | 0x80;
    var h = Array.prototype.map.call(b, function (x) { return ("0" + x.toString(16)).slice(-2); }).join("");
    return h.slice(0, 8) + "-" + h.slice(8, 12) + "-" + h.slice(12, 16) + "-" + h.slice(16, 20) + "-" + h.slice(20);
  }

  function saveChoice(yes, id) {
    document.cookie = COOKIE + "=" + VERSION + (yes ? "-yes" : "-no") + "." + id +
      "; max-age=" + (yes ? ACCEPT_AGE : DECLINE_AGE) + "; path=/; SameSite=Lax" +
      (location.protocol === "https:" ? "; Secure" : "");
  }

  // Sends one record to the audit trail. Never blocks or breaks the banner:
  // if the request fails, the visitor's choice still applies.
  function logChoice(action, yes, id) {
    if (!LOG_URL) return;
    try {
      fetch(LOG_URL, {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ id: id, action: action, analytics: yes, version: VERSION, page: location.pathname }),
        keepalive: true,
        credentials: "omit"
      }).catch(function () {});
    } catch (e) { /* ignore */ }
  }

  function gaConfigured() {
    return /^G-[A-Z0-9]+$/.test(GA_ID) && GA_ID !== "G-XXXXXXXXXX";
  }

  function loadGA() {
    if (!gaConfigured() || window.__pnGA) return;
    window.__pnGA = true;
    window["ga-disable-" + GA_ID] = false;
    window.dataLayer = window.dataLayer || [];
    window.gtag = function () { window.dataLayer.push(arguments); };
    window.gtag("js", new Date());
    // Analytics only: switch off Google's advertising features, whatever the admin settings say
    window.gtag("config", GA_ID, {
      allow_google_signals: false,
      allow_ad_personalization_signals: false
    });
    var s = document.createElement("script");
    s.async = true;
    s.src = "https://www.googletagmanager.com/gtag/js?id=" + encodeURIComponent(GA_ID);
    document.head.appendChild(s);
  }

  function removeGA() {
    if (gaConfigured()) window["ga-disable-" + GA_ID] = true;
    var names = document.cookie.split("; ").map(function (c) { return c.split("=")[0]; })
      .filter(function (n) { return n === "_ga" || n === "_gid" || n.indexOf("_ga_") === 0 || n.indexOf("_gat") === 0; });
    var parts = location.hostname.split(".");
    var domains = [""];
    for (var i = 0; i < parts.length - 1; i++) {
      var d = parts.slice(i).join(".");
      domains.push(d, "." + d);
    }
    names.forEach(function (n) {
      domains.forEach(function (d) {
        document.cookie = n + "=; max-age=0; path=/" + (d ? "; domain=" + d : "");
      });
    });
  }

  function css() {
    var brand = colour(C.colors.brand, DEFAULTS.colors.brand);
    var text = colour(C.colors.text, DEFAULTS.colors.text);
    var bg = colour(C.colors.background, DEFAULTS.colors.background);
    var focus = colour(C.colors.focus, DEFAULTS.colors.focus);
    var body = font(C.fonts.body, DEFAULTS.fonts.body);
    var head = font(C.fonts.heading, DEFAULTS.fonts.heading);
    return "" +
      "#pn-cookie{position:fixed;left:0;right:0;bottom:0;z-index:2147483000;padding:12px 12px calc(12px + env(safe-area-inset-bottom,0px));font:400 15px/1.5 " + body + ";color:" + text + ";color-scheme:light;pointer-events:none}" +
      "#pn-cookie[hidden]{display:none}" +
      ".pnc-box{pointer-events:auto;max-width:760px;margin:0 auto;background:" + bg + ";border:2px solid " + brand + ";border-radius:18px;padding:18px 20px;box-shadow:0 8px 30px rgba(0,0,0,.25)}" +
      ".pnc-box h2{margin:0 0 6px;font:700 20px/1.2 " + head + ";color:" + text + "}" +
      ".pnc-box p{margin:0 0 12px}.pnc-box a{color:" + brand + "}" +
      ".pnc-row{display:flex;flex-wrap:wrap;gap:10px}" +
      ".pnc-btn{font:500 16px " + body + ";background:" + brand + ";color:" + bg + ";border:2px solid " + brand + ";border-radius:999px;padding:10px 20px;cursor:pointer}" +
      ".pnc-alt{background:" + bg + ";color:" + brand + "}" +
      ".pnc-btn:focus-visible,.pnc-box a:focus-visible,.pnc-opt input:focus-visible{outline:3px solid " + focus + ";outline-offset:2px}" +
      ".pnc-opt{display:flex;gap:12px;align-items:flex-start;margin:0 0 12px;cursor:pointer}" +
      ".pnc-opt input{width:22px;height:22px;margin:2px 0 0;accent-color:" + brand + ";flex:0 0 auto}";
  }

  function html() {
    return '<div class="pnc-box">' +
      '<div id="pn-view-main">' +
      '<h2 id="pn-title-main">' + esc(T.title) + '</h2>' +
      '<p>' + esc(T.intro) + ' <a href="' + esc(C.policyUrl) + '">' + esc(T.policyLink) + '</a></p>' +
      '<div class="pnc-row">' +
      '<button type="button" class="pnc-btn" data-act="accept">' + esc(T.accept) + '</button>' +
      '<button type="button" class="pnc-btn" data-act="reject">' + esc(T.reject) + '</button>' +
      '<button type="button" class="pnc-btn pnc-alt" data-act="manage">' + esc(T.manage) + '</button>' +
      '</div></div>' +
      '<div id="pn-view-prefs" hidden>' +
      '<h2 id="pn-title-prefs">' + esc(T.settingsTitle) + '</h2>' +
      '<label class="pnc-opt"><input type="checkbox" checked disabled><span><strong>' + esc(T.essentialName) + '</strong><br>' + esc(T.essentialDesc) + '</span></label>' +
      '<label class="pnc-opt"><input type="checkbox" id="pn-analytics"><span><strong>' + esc(T.analyticsName) + '</strong><br>' + esc(T.analyticsDesc) + '</span></label>' +
      '<div class="pnc-row">' +
      '<button type="button" class="pnc-btn" data-act="save">' + esc(T.save) + '</button>' +
      '<button type="button" class="pnc-btn pnc-alt" data-act="cancel">' + esc(T.cancel) + '</button>' +
      '</div></div></div>';
  }

  function pad() {
    document.body.style.paddingBottom = root.hidden ? "" : root.offsetHeight + "px";
  }

  function show(view) {
    var prefs = view === "prefs";
    root.querySelector("#pn-view-main").hidden = prefs;
    root.querySelector("#pn-view-prefs").hidden = !prefs;
    root.setAttribute("aria-labelledby", prefs ? "pn-title-prefs" : "pn-title-main");
    root.hidden = false;
    pad();
  }

  function hide() {
    root.hidden = true;
    pad();
    if (lastFocus && lastFocus.focus) { lastFocus.focus(); lastFocus = null; }
  }

  function choose(yes) {
    var before = readChoice();   // null if no valid choice for this version yet
    var state = readState();
    var id = (state && state.id) || newId();
    saveChoice(yes, id);
    if (yes) loadGA(); else removeGA();
    if (before !== yes) {
      var action = before === null ? (yes ? "accept" : "reject") : (yes ? "changed" : "withdrawn");
      logChoice(action, yes, id);
    }
    hide();
  }

  function openSettings(from) {
    lastFocus = from || null;
    root.querySelector("#pn-analytics").checked = readChoice() === true;
    show("prefs");
    root.querySelector("#pn-analytics").focus();
  }

  function build() {
    var style = document.createElement("style");
    style.textContent = css();
    document.head.appendChild(style);
    root = document.createElement("div");
    root.id = "pn-cookie";
    root.hidden = true;
    root.setAttribute("role", "dialog");
    root.setAttribute("aria-modal", "false");
    root.innerHTML = html();
    document.body.appendChild(root);

    root.addEventListener("click", function (ev) {
      var act = ev.target && ev.target.getAttribute && ev.target.getAttribute("data-act");
      if (!act) return;
      if (act === "accept") choose(true);
      else if (act === "reject") choose(false);
      else if (act === "manage") openSettings(null);
      else if (act === "save") choose(root.querySelector("#pn-analytics").checked);
      else if (act === "cancel") { if (readChoice() === null) show("main"); else hide(); }
    });
    document.addEventListener("keydown", function (ev) {
      if (ev.key === "Escape" && !root.hidden && readChoice() !== null) hide();
    });
    window.addEventListener("resize", pad);

    document.querySelectorAll("[data-cookie-settings]").forEach(function (el) {
      el.addEventListener("click", function (ev) { ev.preventDefault(); openSettings(el); });
    });
    window.pnOpenCookieSettings = function () { openSettings(null); };
  }

  function init() {
    if (!gaConfigured()) {
      // Nothing to ask consent for yet. Leave the footer link harmless.
      if (window.console) console.warn("Cookie control: no valid gaId in consent-config.js, so no banner is shown.");
      return;
    }
    build();
    var choice = readChoice();
    if (choice === true) loadGA();
    else removeGA(); // clear any analytics cookies set before consent
    if (choice === null) show("main");
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
  else init();
})();
